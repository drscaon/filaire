"""Animated GIF of a coiled handset cord pulled and let go: simulated in MuJoCo, rendered in Blender.

Development tool, not part of the package. Needs the dev extras, Pillow and
Blender as a Python module (`pip install bpy`, Python 3.13):

    python scripts/coil_gif.py [--out docs/images/coil.gif] [--samples 24]
    python scripts/coil_gif.py --plot coil.csv      # simulate only: length of the cord over time

The cord is generated by Filaire, exported to OpenUSD and read back from the
file, as in `filaire sim-test`. Its top plug is held in a clamp; the cord
first hangs under its own weight, then a gripper takes the bottom plug, pulls
it down and lets go: the coil springs back, overshoots a little and settles
on its hanging length. Nothing is scripted after the release: the motion is
the coil's axial spring, bending and damping from the file, and gravity.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import mujoco
import numpy as np
from pxr import Usd
from scipy.spatial.transform import Rotation

from filaire import generate_scene, write_outputs
from filaire.sim.mujoco_model import _spec, add_cable, coarsen, transformed
from filaire.sim.usd_reader import cable_paths, read_cable

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from drop_gif import make_gif, object_tracks  # noqa: E402

COILED = 0.35  # m of coil (the straight leads come on top)
TOP = 1.15  # m, height of the clamped plug
PULL = 0.45  # m, how far the gripper pulls the bottom plug down
# timeline (s): settle unseen (the cord starts straight at its rest length), then on screen:
# hang, pull, hold, release and retract
T_SETTLE = 2.0
T_GRAB, T_PULL, T_HOLD, T_END = 0.6, 1.2, 0.3, 2.6
DT = 5e-4
STEEL = (0.55, 0.56, 0.58, 1)


def make_cable(tmp: Path) -> tuple[Path, str]:
    scene = generate_scene(
        "coiled_handset", count=1, layout="straight", length=COILED, seed=3, color="#1c1c1c"
    )
    folder = write_outputs(scene, tmp)
    return folder / "filaire_coiled_handset.usdc", scene.cables[0].name


def _weld(spec, name: str, body: str, mocap: str):
    eq = spec.add_equality(
        name=name, type=mujoco.mjtEq.mjEQ_WELD, objtype=mujoco.mjtObj.mjOBJ_BODY, name1=body, name2=mocap
    )
    eq.data = np.r_[np.zeros(6), [1, 0, 0, 0], 1.0, 0.0]  # the two frames coincide
    eq.solref = [0.005, 1.0]
    return eq


def smooth(t: float) -> float:
    t = min(max(t, 0.0), 1.0)
    return t * t * t * (10 - 15 * t + 6 * t * t)  # smootherstep: no jerk at the ends


def simulate(usd: Path, fps: int):
    stage = Usd.Stage.Open(str(usd))
    c = read_cable(stage, cable_paths(stage)[0])
    # hanging straight down from end A: the cord's x axis to -z, end A's plug up
    R = Rotation.from_euler("y", 90, degrees=True).as_matrix()
    top = c.segments[0].position - c.segments[0].rotation[:, 0] * c.segments[0].capsule[1] / 2
    fine = transformed(c, R, np.array([0, 0, TOP]) - R @ top)
    coarse = coarsen(fine, 80)
    spec = _spec(DT, 0.5)
    init_pose = add_cable(spec, coarse, "c0_", DT)
    for g in spec.geoms:
        g.solref = [max(4 * DT, 0.002), 1.0]
    for m in ("clamp", "hand"):
        spec.worldbody.add_body(name=m, mocap=True)
    _weld(spec, "hold_top", "c0_end_a", "clamp")
    _weld(spec, "grip", "c0_end_b", "hand")
    model = spec.compile()
    data = mujoco.MjData(model)
    init_pose(model, data, 0.0)
    mujoco.mj_forward(model, data)
    a, b = model.body("c0_end_a").id, model.body("c0_end_b").id
    clamp, hand = model.body("clamp").mocapid[0], model.body("hand").mocapid[0]
    data.mocap_pos[clamp], data.mocap_quat[clamp] = data.xpos[a], data.xquat[a]
    grip = model.equality("grip").id
    data.eq_active[grip] = 0
    grab_pos = None

    steps = round(1 / fps / DT)
    t_release = T_GRAB + T_PULL + T_HOLD
    n_frames = int((t_release + T_END) * fps) + 1
    frames, hand_track, length = [], [], []
    t0 = time.time()
    while data.time < T_SETTLE:
        mujoco.mj_step(model, data)
    for f in range(n_frames):
        for _ in range(steps if f else 0):
            t = data.time - T_SETTLE
            if t >= T_GRAB and grab_pos is None:  # the gripper takes the plug where it hangs
                grab_pos = data.xpos[b].copy()
                data.mocap_pos[hand], data.mocap_quat[hand] = grab_pos, data.xquat[b]
                data.eq_active[grip] = 1
            if grab_pos is not None:
                data.mocap_pos[hand] = grab_pos - [0, 0, PULL * smooth((t - T_GRAB) / T_PULL)]
            if t >= t_release:
                data.eq_active[grip] = 0
            mujoco.mj_step(model, data)
        frame = {}
        for i in range(len(coarse.segments)):
            bid = model.body(f"c0_seg{i}").id
            M = np.eye(4)
            M[:3, :3], M[:3, 3] = data.xmat[bid].reshape(3, 3), data.xpos[bid]
            frame[(0, f"seg{i}")] = M
        for side, bid in (("a", a), ("b", b)):
            M = np.eye(4)
            M[:3, :3], M[:3, 3] = data.xmat[bid].reshape(3, 3), data.xpos[bid]
            frame[(0, f"end_{side}")] = M
        frames.append(frame)
        H = np.eye(4)
        if grab_pos is None:
            H[:3, 3] = data.xpos[b]
        else:
            H[:3, 3] = data.mocap_pos[hand]
        hand_track.append(H)
        length.append((data.time - T_SETTLE, float(data.xpos[a][2] - data.xpos[b][2])))
    print(f"simulated {data.time:.1f} s ({len(frames)} frames) in {time.time() - t0:.0f} s", flush=True)
    if data.warning[mujoco.mjtWarning.mjWARN_BADQACC].number or not np.isfinite(data.qpos).all():
        raise SystemExit("simulation unstable: lower DT")
    return [fine], [coarse], frames, hand_track, length, t_release


def coil_mesh(cable, frames, per_turn: int = 14, sides: int = 8):
    """The cord as one wire mesh per frame, wound along the simulated axis.

    The segments' own coil pieces are rigid: stretched, gaps open between them. Here the wire
    is a helix along the axis through the simulated joints, with a fixed number of turns per
    segment (the turns spread as the coil stretches), on the axis in the straight leads.
    Returns (faces, points[frame, vertex, 3])."""
    a = cable.attrs
    D, p, wire = (
        float(a["filaire:coil:diameter"]),
        float(a["filaire:coil:pitch"]),
        float(a["filaire:coil:wireDiameter"]),
    )
    la, lb = map(float, a["filaire:coil:leads"])
    L = np.array([sg.capsule[1] for sg in cable.segments])
    s_rest = np.r_[0.0, np.cumsum(L)]  # rest arc length at the joints
    n = max(int(s_rest[-1] / p * per_turn), 16)
    s = np.linspace(0.0, s_rest[-1], n)
    seg = np.clip(np.searchsorted(s_rest, s, side="right") - 1, 0, len(L) - 1)
    u = (s - s_rest[seg]) / L[seg]
    ramp = 1.2 * D
    w = np.ones(n)
    for start, x in ((la, s), (lb, s_rest[-1] - s)):
        t = np.clip((x - start) / ramp, 0.0, 1.0)
        w = np.minimum(w, t * t * (3 - 2 * t))
    phi = 2 * np.pi * s / p
    ring = np.linspace(0, 2 * np.pi, sides, endpoint=False)
    faces = [
        (i * sides + k, i * sides + (k + 1) % sides, (i + 1) * sides + (k + 1) % sides, (i + 1) * sides + k)
        for i in range(n - 1)
        for k in range(sides)
    ]
    out = []
    for fr in frames:
        mats = [fr[(0, f"seg{i}")] for i in range(len(L))]
        p0 = np.array([M[:3, 3] - M[:3, 0] * L[i] / 2 for i, M in enumerate(mats)])
        p1 = np.array([M[:3, 3] + M[:3, 0] * L[i] / 2 for i, M in enumerate(mats)])
        J = np.vstack([p0[:1], 0.5 * (p1[:-1] + p0[1:]), p1[-1:]])  # joints: across the slides' gaps
        axis = J[seg] + (J[seg + 1] - J[seg]) * u[:, None]
        t = np.gradient(axis, axis=0)
        t /= np.linalg.norm(t, axis=1, keepdims=True)
        # rotation-minimising frame along the axis, from the first segment's y axis
        e1 = np.empty_like(axis)
        e1[0] = mats[0][:3, 1]
        for i in range(1, n):
            v = e1[i - 1] - t[i] * (e1[i - 1] @ t[i])
            e1[i] = v / np.linalg.norm(v)
        e2 = np.cross(t, e1)
        radial = np.cos(phi)[:, None] * e1 + np.sin(phi)[:, None] * e2
        pts = axis + (D / 2 * w)[:, None] * radial
        tw = np.gradient(pts, axis=0)
        tw /= np.linalg.norm(tw, axis=1, keepdims=True)
        nn = w[:, None] * radial + (1 - w)[:, None] * e1  # the wire's frame: steady along a lead
        nn -= tw * np.sum(nn * tw, axis=1, keepdims=True)
        nn /= np.linalg.norm(nn, axis=1, keepdims=True)
        bb = np.cross(tw, nn)
        r = wire / 2
        verts = pts[:, None, :] + r * (
            np.cos(ring)[None, :, None] * nn[:, None, :] + np.sin(ring)[None, :, None] * bb[:, None, :]
        )
        out.append(verts.reshape(-1, 3))
    return np.array(faces, dtype=np.int32), np.array(out, dtype=np.float32)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/images/coil.gif")
    ap.add_argument("--fps", type=int, default=25)
    ap.add_argument("--samples", type=int, default=24)
    ap.add_argument("--size", default="540x720")
    ap.add_argument("--frames", default=None, help="keep the rendered PNG frames in this folder")
    ap.add_argument("--plot", default=None, help="simulate only, write time and length to this CSV")
    args = ap.parse_args(argv)
    w, h = map(int, args.size.split("x"))
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        usd, name = make_cable(tmp / "cable")
        fine, coarse, frames, hand_track, length, t_release = simulate(usd, args.fps)
        if args.plot:
            Path(args.plot).write_text("t,length\n" + "".join(f"{a:.3f},{b:.4f}\n" for a, b in length))
            print(args.plot)
            return
        tracks = {k: v for k, v in object_tracks(fine, coarse, frames).items() if "/End_" in k}
        top = frames[0][(0, "end_a")][:3, 3]
        clamp = {"type": "box", "pos": list(top + [0, 0, 0.03]), "size": [0.02, 0.02, 0.015], "color": STEEL}
        bar = {"type": "cylinder", "pos": list(top + [0, 0.15, 0.045]), "size": [0.008, 0.15],
               "euler": [90, 0, 0], "color": STEEL}  # fmt: skip
        # the gripper: a steel jaw just under the bottom plug, shown while it holds the cord
        jaw = {"type": "cylinder", "size": [0.012, 0.012], "color": (0.2, 0.2, 0.22, 1), "pos": [0, 0, 0]}
        n_hold = int(round(t_release * args.fps))
        n_grab = int(round(T_GRAB * args.fps))
        far = np.eye(4)
        far[:3, 3] = [0, 0, -5]  # out of sight under the floor
        jaw_track = []
        for f, H in enumerate(hand_track):
            if n_grab <= f <= n_hold:
                M = H.copy()
                M[2, 3] -= 0.03  # under the plug's body
                jaw_track.append(M)
            elif f > n_hold:  # let go: the gripper drops away
                M = hand_track[n_hold].copy()
                M[2, 3] -= 0.03 + 0.4 * (f - n_hold) / args.fps
                jaw_track.append(M)
            else:
                jaw_track.append(far)
        faces, points = coil_mesh(fine[0], frames)
        np.savez(tmp / "coil.npz", faces=faces, points=points)
        # a dark wall behind: the floor's horizon would cut the portrait frame
        wall = {"type": "box", "pos": [0, 0.7, 1.5], "size": [4.0, 0.02, 1.5],
                "color": (0.11, 0.115, 0.12, 1), "metallic": 0.0, "roughness": 0.9}  # fmt: skip
        mid = 0.64
        job = {
            "cables": [{"usd": str(usd), "name": name}],
            "tracks": {key: [m.tolist() for m in mats] for key, mats in tracks.items()},
            "frames": len(frames),
            "size": [w, h],
            "camera": [0.32, -1.36, mid + 0.08, 0.0, 0.0, mid],
            "lens": 36,  # portrait: Blender fits the 36 mm sensor to the height
            "obstacles": [clamp, bar, wall],
            "hide_segments": True,
            "deform": {"npz": str(tmp / "coil.npz"), "color": [0.012, 0.012, 0.012, 1], "roughness": 0.45},
            "movers": [{"ob": jaw, "track": [m.tolist() for m in jaw_track]}],
            "floor_markings": True,
            "samples": args.samples,
            "out_dir": args.frames or str(tmp / "frames"),
        }
        (tmp / "job.json").write_text(json.dumps(job))
        t0 = time.time()
        subprocess.run(
            [sys.executable, str(HERE / "render_blender.py"), "anim", str(tmp / "job.json")],
            check=True,
            stdout=subprocess.DEVNULL,
            env={**os.environ},
        )
        print(f"rendered {len(frames)} frames in {time.time() - t0:.0f} s", flush=True)
        make_gif(sorted(Path(job["out_dir"]).glob("*.png")), Path(args.out), args.fps)
    print(Path(args.out))


if __name__ == "__main__":
    main()
