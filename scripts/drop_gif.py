"""Animated GIF of cables falling on the floor: simulated in MuJoCo, rendered in Blender.

Development tool, not part of the package. Needs the dev extras, Pillow and
Blender as a Python module (`pip install bpy`, Python 3.13):

    python scripts/drop_gif.py [--out docs/images/drop.gif] [--seconds 2.2] [--samples 24]

The cables are generated by Filaire, exported to OpenUSD and read back from
the files, as in `filaire sim-test`. Straight, steeply tilted and stacked at
different heights and angles, they are dropped together onto a bar lying on
the floor: one end hits first, the cables fold over the bar and each other,
and come to rest.
For speed each cable is simulated with at most `--links` rigid links (groups
of segments merged, springs in series, same bending stiffness: see
`filaire.sim.mujoco_model.coarsen`); each group of segments then follows its
link rigidly in the render.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import mujoco
import numpy as np
from pxr import Usd
from scipy.spatial.transform import Rotation

from filaire import generate_scene, write_outputs
from filaire.sim.mujoco_model import coarsen, scene_model, transformed
from filaire.sim.usd_reader import cable_paths, read_cable

HERE = Path(__file__).resolve().parent

# preset, generation options, drop: (x, y, height of the centre, yaw°, tilt°)
# Steep tilts: one end hits first and the cable folds over the bar and the others.
CABLES = [
    ("power_c13", dict(seed=5, ends={"a": "c13_plug", "b": "cee77_plug"}), (0.00, 0.02, 0.42, 80, 35)),
    ("ethernet", dict(seed=2, color="#2a6fbf", ends={"b": "rj45_plug"}), (0.06, -0.02, 0.58, 115, -45)),
    ("usb_c", dict(seed=3, color="#f0f0ee", ends={"b": "usb_c_plug"}), (-0.07, 0.03, 0.74, 60, 50)),
    ("audio_jack", dict(seed=4, color="#c0392b", ends={"b": "jack35_plug"}), (0.10, 0.04, 0.90, 100, -55)),
    ("m12_sensor", dict(seed=2, color="#e88a2a", ends={"b": "stripped"}), (-0.12, -0.03, 1.06, 75, 40)),
]
LENGTH = 0.7
# a bar lying on the floor across the drop zone, for the cables to fall on
OBSTACLES = [{"type": "cylinder", "pos": [0.0, 0.0, 0.05], "size": [0.05, 0.3], "euler": [0, 90, 0]}]
DT = 5e-4


def make_cables(tmp: Path) -> list[tuple[str, Path, str]]:
    out = []
    for preset, opts, _drop in CABLES:
        scene = generate_scene(preset, count=1, layout="straight", length=LENGTH, **opts)
        folder = write_outputs(scene, tmp)
        out.append((preset, folder / f"filaire_{preset}.usdc", scene.cables[0].name))
    return out


def drop_pose(cable, x, y, z, yaw, tilt):
    """Centre the authored cable on (x, y, z), turn it by yaw about z and tilt it about x."""
    pts = np.array([s.position for s in cable.segments])
    centre = 0.5 * (pts.min(0) + pts.max(0))
    R = Rotation.from_euler("zx", [yaw, tilt], degrees=True).as_matrix()
    return R, np.array([x, y, z]) - R @ centre


def simulate(cables_usd, seconds: float, fps: int, links: int):
    fine, coarse, poses = [], [], []
    for (_preset, path, _name), (_p, _o, drop) in zip(cables_usd, CABLES, strict=True):
        stage = Usd.Stage.Open(str(path))
        c = read_cable(stage, cable_paths(stage)[0])
        R, t = drop_pose(c, *drop)
        moved = transformed(c, R, t)
        fine.append(moved)
        coarse.append(coarsen(moved, links))
        poses.append((R, t))
    model, init = scene_model(coarse, dt=DT, obstacles=OBSTACLES)
    data = mujoco.MjData(model)
    init(data)
    steps_per_frame = round(1 / fps / model.opt.timestep)
    frames = []
    t0 = time.time()
    for f in range(int(seconds * fps) + 1):
        if f:
            for _ in range(steps_per_frame):
                mujoco.mj_step(model, data)
        frame = {}
        for k in range(len(coarse)):
            for name in [f"seg{i}" for i in range(len(coarse[k].segments))] + ["end_a", "end_b"]:
                try:
                    b = model.body(f"c{k}_{name}")
                except KeyError:
                    continue
                M = np.eye(4)
                M[:3, :3] = data.xmat[b.id].reshape(3, 3)
                M[:3, 3] = data.xpos[b.id]
                frame[(k, name)] = M
        frames.append(frame)
    print(f"simulated {seconds} s ({len(frames)} frames) in {time.time() - t0:.0f} s", flush=True)
    if data.warning[mujoco.mjtWarning.mjWARN_BADQACC].number or not np.isfinite(data.qpos).all():
        raise SystemExit("simulation unstable: lower DT")
    return fine, coarse, poses, frames


def object_tracks(fine, coarse, frames):
    """World matrix of every Blender object to move, per frame, keyed by '<k>/Segments/seg_012'.

    A fine segment follows its coarse link rigidly: world(t) = link(t) · link(0)⁻¹ · segment(0).
    """
    tracks = {}
    for k, (cf, cc) in enumerate(zip(fine, coarse, strict=True)):
        g = int(np.ceil(len(cf.segments) / len(cc.segments)))
        for i, seg in enumerate(cf.segments):
            S0 = np.eye(4)
            S0[:3, :3], S0[:3, 3] = seg.rotation, seg.position
            rel = np.linalg.inv(frames[0][(k, f"seg{i // g}")]) @ S0
            tracks[f"{k}/Segments/seg_{i:03d}"] = [fr[(k, f"seg{i // g}")] @ rel for fr in frames]
        for side in ("a", "b"):
            if (k, f"end_{side}") in frames[0]:
                tracks[f"{k}/End_{side.upper()}/Body"] = [fr[(k, f"end_{side}")] for fr in frames]
    return tracks


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/images/drop.gif")
    ap.add_argument("--seconds", type=float, default=2.0)
    ap.add_argument("--fps", type=int, default=25)
    ap.add_argument("--links", type=int, default=60)
    ap.add_argument("--samples", type=int, default=24)
    ap.add_argument("--size", default="800x450")
    ap.add_argument("--frames", default=None, help="keep the rendered PNG frames in this folder")
    args = ap.parse_args(argv)
    w, h = map(int, args.size.split("x"))
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        cables = make_cables(tmp / "cables")
        fine, coarse, poses, frames = simulate(cables, args.seconds, args.fps, args.links)
        tracks = object_tracks(fine, coarse, frames)
        job = {
            "cables": [{"usd": str(path), "name": name} for _p, path, name in cables],
            "tracks": {key: [m.tolist() for m in mats] for key, mats in tracks.items()},
            "frames": len(frames),
            "size": [w, h],
            "camera": [0.78, -0.95, 0.62, 0.0, 0.0, 0.13],
            "lens": 36,
            "obstacles": OBSTACLES,
            "samples": args.samples,
            "out_dir": args.frames or str(tmp / "frames"),
        }
        (tmp / "job.json").write_text(json.dumps(job))
        t0 = time.time()
        subprocess.run(
            [sys.executable, str(HERE / "render_blender.py"), "anim", str(tmp / "job.json")],
            check=True,
            stdout=subprocess.DEVNULL,
            env={**os.environ},
        )
        print(f"rendered {len(frames)} frames in {time.time() - t0:.0f} s", flush=True)
        make_gif(sorted(Path(job["out_dir"]).glob("*.png")), Path(args.out), args.fps)
    print(Path(args.out))


def make_gif(paths, out: Path, fps: int, hold: float = 1.2):
    from PIL import Image

    frames = [Image.open(p).convert("RGB") for p in paths]
    # one shared palette from a few frames, so the floor does not flicker
    sample = Image.new("RGB", (frames[0].width, frames[0].height * 3))
    for i, f in enumerate((frames[0], frames[len(frames) // 2], frames[-1])):
        sample.paste(f, (0, i * frames[0].height))
    # octree keeps the small, saturated cable colours that median cut merges into the grey floor
    pal = sample.quantize(colors=255, method=Image.Quantize.FASTOCTREE)
    q = [f.quantize(palette=pal, dither=Image.Dither.NONE) for f in frames]
    durations = [round(1000 / fps)] * len(q)
    durations[-1] = int(hold * 1000)  # a look at the pile before the loop
    out.parent.mkdir(parents=True, exist_ok=True)
    q[0].save(out, save_all=True, append_images=q[1:], duration=durations, loop=0, optimize=True)


if __name__ == "__main__":
    main()
